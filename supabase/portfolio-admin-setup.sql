-- Run this in Supabase SQL Editor for the portfolio admin dashboard.
-- This schema is for the Next.js portfolio project, not any other Supabase project.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category text not null default 'Reels & Shorts',
  video_url text,
  thumbnail_url text,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.projects add column if not exists description text;
alter table public.projects add column if not exists category text not null default 'Reels & Shorts';
alter table public.projects add column if not exists video_url text;
alter table public.projects add column if not exists thumbnail_url text;
alter table public.projects add column if not exists is_published boolean not null default true;
alter table public.projects add column if not exists created_at timestamptz not null default now();

create table if not exists public.portfolio_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
alter table public.portfolio_admins enable row level security;

drop policy if exists "Public can view published portfolio projects" on public.projects;
create policy "Public can view published portfolio projects"
on public.projects for select
using (is_published = true);

drop policy if exists "Admins can view all portfolio projects" on public.projects;
create policy "Admins can view all portfolio projects"
on public.projects for select to authenticated
using (exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()));

drop policy if exists "Admins can insert portfolio projects" on public.projects;
create policy "Admins can insert portfolio projects"
on public.projects for insert to authenticated
with check (exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()));

drop policy if exists "Admins can update portfolio projects" on public.projects;
create policy "Admins can update portfolio projects"
on public.projects for update to authenticated
using (exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()));

drop policy if exists "Admins can delete portfolio projects" on public.projects;
create policy "Admins can delete portfolio projects"
on public.projects for delete to authenticated
using (exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()));

drop policy if exists "Admins can read own admin row" on public.portfolio_admins;
create policy "Admins can read own admin row"
on public.portfolio_admins for select to authenticated
using (user_id = auth.uid());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('project-covers', 'project-covers', true, 10485760, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = true;

drop policy if exists "Public can view project covers" on storage.objects;
create policy "Public can view project covers"
on storage.objects for select
using (bucket_id = 'project-covers');

drop policy if exists "Portfolio admins can upload project covers" on storage.objects;
create policy "Portfolio admins can upload project covers"
on storage.objects for insert to authenticated
with check (bucket_id = 'project-covers' and exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()));

drop policy if exists "Portfolio admins can update project covers" on storage.objects;
create policy "Portfolio admins can update project covers"
on storage.objects for update to authenticated
using (bucket_id = 'project-covers' and exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()))
with check (bucket_id = 'project-covers' and exists (select 1 from public.portfolio_admins a where a.user_id = auth.uid()));

